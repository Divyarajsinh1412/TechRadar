def generate_technology_dataset(output_path: str = "data/sample_technology_data.csv", random_seed: int = 42) -> pd.DataFrame:
    """
    Generate longitudinal monthly technology analytics dataset covering 2021 to 2025.
    Creates 60 monthly periods per technology.
    """
    random.seed(random_seed)
    np.random.seed(random_seed)

    rows = []
    
    # Generate 60 monthly periods: 2021-01 to 2025-12
    dates = []
    for year in range(2021, 2026):
        for month in range(1, 13):
            dates.append((year, month, f"{year}-{month:02d}-01"))

    total_months = len(dates)

    for cat_name, tech_list in TECH_CATEGORIES.items():
        for tech in tech_list:
            profile = TECH_PROFILES.get(tech, {
                "base_jobs": 1500, "base_interest": 70.0, "base_adoption": 70.0,
                "base_salary": 120000, "momentum": 0.05
            })
            
            base_jobs = profile["base_jobs"]
            base_interest = profile["base_interest"]
            base_adoption = profile["base_adoption"]
            base_salary = profile["base_salary"]
            momentum = profile["momentum"]

            for t_idx, (yr, mo, date_str) in enumerate(dates):
                # Time progression factor from 0 to 1
                t_factor = t_idx / (total_months - 1)
                
                # Compound growth or decline with realistic noise
                growth_multiplier = (1.0 + momentum) ** (t_factor * 4.0)
                noise_jobs = np.random.normal(1.0, 0.04)
                noise_interest = np.random.normal(0.0, 1.5)
                noise_salary = np.random.normal(0.0, 1200)

                # Seasonal effect (Q1 tech hiring spike, Q4 slowdown)
                seasonality = 1.0 + 0.04 * np.sin(2 * np.pi * (mo - 1) / 12)

                job_postings = int(max(50, base_jobs * growth_multiplier * seasonality * noise_jobs))
                dev_interest = round(float(np.clip(base_interest + (momentum * 25.0 * t_factor) + noise_interest, 10.0, 100.0)), 2)
                co_adoption = round(float(np.clip(base_adoption + (momentum * 20.0 * t_factor), 10.0, 100.0)), 2)
                
                salary_growth = 1.0 + (0.035 * t_factor * 4.0) + (momentum * 0.05 * t_factor)
                avg_salary = round((base_salary * salary_growth + noise_salary) / 250) * 250

                github_act = round(float(np.clip(dev_interest * 0.95 + np.random.normal(0, 3), 10.0, 100.0)), 2)
                skill_dem = round(float(np.clip(co_adoption * 0.70 + dev_interest * 0.30, 10.0, 100.0)), 2)
                
                # Growth rate percentage compared to base
                growth_rate = round(float((growth_multiplier - 1.0) * 100 + np.random.normal(0, 2)), 2)

                rows.append({
                    "technology": tech,
                    "category": cat_name,
                    "year": yr,
                    "month": mo,
                    "date": date_str,
                    "job_postings": job_postings,
                    "developer_interest": dev_interest,
                    "company_adoption": co_adoption,
                    "average_salary": avg_salary,
                    "github_activity": github_act,
                    "skill_demand": skill_dem,
                    "growth_rate": growth_rate
                })

    df = pd.DataFrame(rows)

    # Intersperse realistic academic data-cleaning challenges:
    # 1. 20 duplicate rows (to demonstrate df.drop_duplicates())
    dup_indices = random.sample(range(len(df)), 20)
    dups = df.iloc[dup_indices].copy()
    df = pd.concat([df, dups], ignore_index=True)

    # 2. 25 missing values in average_salary (NaN)
    sal_nan_idx = random.sample(range(len(df)), 25)
    df.loc[sal_nan_idx, "average_salary"] = np.nan

    # 3. 15 missing values in developer_interest (NaN)
    dev_nan_idx = random.sample(range(len(df)), 15)
    df.loc[dev_nan_idx, "developer_interest"] = np.nan

    # 4. Inconsistent technology string casing / aliases for string normalization
    aliases = {
        "Python": ["python", "PYTHON"],
        "React": ["reactjs", "REACT"],
        "Go": ["golang", "GOLANG"],
        "Kubernetes": ["k8s", "K8s"],
        "PostgreSQL": ["postgres", "POSTGRESQL"]
    }
    for tech_name, alias_list in aliases.items():
        matches = df[df["technology"] == tech_name].index
        if len(matches) > 3:
            chosen = random.sample(list(matches), 3)
            for idx in chosen:
                df.loc[idx, "technology"] = random.choice(alias_list)

    # 5. Outliers for IQR demonstration (4 extremely low, 4 extremely high)
    outlier_idx = random.sample(range(len(df)), 8)
    df.loc[outlier_idx[0:4], "average_salary"] = [15000, 18000, 22000, 25000]
    df.loc[outlier_idx[4:8], "average_salary"] = [450000, 580000, 720000, 890000]

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    df.to_csv(output_path, index=False)
    print(f"Generated sample technology dataset at {output_path} with {len(df)} records.")
    return df

